def _excl(model_type, areas):
    a = (areas or {}).get(model_type) or {}
    if a.get("excl"):
        return float(a["excl"])
    m = re.match(r"\s*(\d{2,3}(?:\.\d+)?)", str(model_type))
    return float(m.group(1)) if m else None


def picker_items(notices):
    """'지금 공고에서 불러오기' — 접수 중·예정 분양 공고의 타입별 최고 분양가·전용면적·납부 비율."""
    out = []
    for n in notices:
        if n.get("is_rental") or n.get("is_pre") or n["status"] not in ("open", "upcoming"):
            continue
        f = ((n.get("decide") or {}).get("funds") or {})
        dep = mid = 0
        for lab, _, pct in f.get("steps", []):
            if "계약" in lab:
                dep += pct
            elif "중도" in lab:
                mid += pct
        ratio = [dep, mid, 100 - dep - mid] if dep and dep + mid <= 100 else None
        models = [m for m in (n.get("models") or []) if m.get("max")]
        if not models:
            continue
        nm = n.get("complex") or n["title"]
        for m in models[:6]:
            ex = _excl(m["type"], n.get("areas"))
            out.append({"t": f"{nm} · {m['type']}", "p": int(m["max"] // 10000), "a": round(ex, 2) if ex else None,
                        "r": ratio, "u": n["url"], "s": n["sido"], "e": (n["rcpt"][1] or n["rcpt"][0])})
    out.sort(key=lambda x: (x["e"], x["t"]))
    return out[:60]


